#!/usr/bin/env python3
"""Copy the installer's kickstart scripts from image/installer/ into the kickstart of the real installer
(image/disk_config/iso.toml) and of the CI install test (image/disk_config/install-test.toml), so both run the exact
same bytes:
  dualboot-guard.sh        -> %pre (the dual-boot safety page)
  dualboot-guard-check.sh  -> %post --nochroot
(The installer's JARVIS pictures are not in the kickstart: a %pre runs after the installer window has loaded its
pictures. tools/release/brand_iso.sh adds them to the ISO as images/product.img instead.)
python3 tools/sync_installer_guard.py [--check]   (--check: exit 1 if a copy is stale)"""
import pathlib, re, sys
Q = "'" * 3   # the TOML literal-string quotes around the kickstart
root = pathlib.Path(__file__).resolve().parent.parent
inst = root / "image/installer"
guard = (inst / "dualboot-guard.sh").read_text()
check = (inst / "dualboot-guard-check.sh").read_text()
BEGIN, END = "# >>> dualboot-guard (generated by tools/sync_installer_guard.py from image/installer/; do not edit here)", "# <<< dualboot-guard"
block = (f"{BEGIN}\n%pre --interpreter=/usr/bin/bash\n{guard.rstrip()}\n%end\n"
         f"%post --nochroot --interpreter=/usr/bin/bash\n{check.rstrip()}\n%end\n{END}\n")
assert Q not in block and not any(l.startswith("%") for l in (guard + check).splitlines())
stale = []
for name in ("iso.toml", "install-test.toml"):
    p = root / "image/disk_config" / name
    t = p.read_text()
    if BEGIN in t:
        new = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n", lambda m: block, t, flags=re.S)
    else:   # first time: at the end of the kickstart contents (after the commands and the other sections)
        a = t.index("contents = " + Q + "\n"); b = t.index("\n" + Q, a + 15) + 1
        new = t[:b] + block + t[b:]
    if new != t:
        stale.append(name)
        if "--check" not in sys.argv: p.write_text(new)
if "--check" in sys.argv and stale: sys.exit("stale installer script copy in: " + ", ".join(stale))
print("updated" if stale else "in sync", *stale)
